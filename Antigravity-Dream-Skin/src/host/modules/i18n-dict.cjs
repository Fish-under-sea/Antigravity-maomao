/**
 * Antigravity Dream Skin — Pure MIT Host & Swarm i18n Dictionary
 *
 * Red-line invariant:
 * - Model names (Gemini 4 Neon/Hydrogen/Flash/Carbon/Argon, Gemini 3.x Pro/Flash,
 *   Claude Sonnet/Opus/Haiku, GPT-*, o1/o3/o4, Orchestrator, Auto, etc.) MUST stay
 *   in original English.
 * - Thinking / reasoning effort labels (Off, Minimal, Low, Medium, High, Extra High,
 *   XHigh, Max, Auto, Thinking) MUST stay in original English.
 */

const PROTECTED_EFFORT_WORDS_SRC =
  "(?:off|minimal|low|medium|med|high|extra[\\s-]?high|x[\\s-]?high|max|maximum|auto|thinking)";

const PROTECTED_MODEL_OR_EFFORT_RE = new RegExp(
  [
    // 1. Standalone thinking/reasoning effort labels (optionally with parenthesized level/tag)
    `^${PROTECTED_EFFORT_WORDS_SRC}(?:\\s*\\(${PROTECTED_EFFORT_WORDS_SRC}\\))?$`,
    // 2. Standalone Orchestrator / Auto labels or combined with effort via separator
    `^(?:orchestrator|auto)(?:\\s*[·•|/\\-]\\s*${PROTECTED_EFFORT_WORDS_SRC})?(?:\\s*\\([^)]{1,28}\\))?$`,
    // 3. Gemini model names (excluding UI labels like "Gemini Models")
    `^(?:google\\s+)?gemini(?!\\s+models?\\b)(?:[\\s-]+(?:\\d+(?:\\.\\d+)*|pro|flash|ultra|nano|live|lite|neon|hydrogen|carbon|argon|exp|experimental|preview|thinking|fast|mini|max|latest|v\\d+|${PROTECTED_EFFORT_WORDS_SRC}|[·•|/\\-])){1,8}(?:\\s*\\([^)]{1,32}\\))?$`,
    // 4. Claude model names (excluding UI labels like "Claude and GPT models")
    `^(?:anthropic\\s+)?claude(?!\\s+and\\b)(?!\\s+models?\\b)(?:[\\s-]+(?:\\d+(?:\\.\\d+)*|sonnet|opus|haiku|instant|thinking|preview|latest|fast|mini|max|${PROTECTED_EFFORT_WORDS_SRC}|[·•|/\\-])){1,8}(?:\\s*\\([^)]{1,32}\\))?$`,
    // 5. OpenAI GPT / o-series model names
    `^(?:openai\\s+)?(?:gpt(?:-[a-z0-9.]+|\\s+\\d[a-z0-9.-]*)|o[134](?:-(?:mini|pro|preview|high|medium|low))?|chatgpt-[a-z0-9.-]+)(?:[\\s-]+(?:\\d+(?:\\.\\d+)*|oss|mini|nano|pro|turbo|preview|latest|\\d+b|${PROTECTED_EFFORT_WORDS_SRC}|[·•|/\\-])){0,6}(?:\\s*\\([^)]{1,32}\\))?$`,
    // 6. Other known model families / codenames (DeepSeek, Qwen, Llama, Mistral, Grok, Sonnet/Opus/Haiku/Neon/Hydrogen/Carbon/Argon)
    `^(?:deepseek|qwen|llama|mistral|mixtral|grok|sonnet|opus|haiku|neon|hydrogen|carbon|argon)(?:[\\s-]+(?:v?\\d+(?:\\.\\d+)*|r\\d+|coder|chat|instruct|pro|flash|mini|max|fast|preview|latest|${PROTECTED_EFFORT_WORDS_SRC}|[·•|/\\-])){0,6}(?:\\s*\\([^)]{1,32}\\))?$`,
  ].join("|"),
  "i"
);

function isProtectedModelOrEffortText(text) {
  if (typeof text !== "string") return false;
  const trimmed = text.trim();
  if (!trimmed || trimmed.length > 96) return false;
  return PROTECTED_MODEL_OR_EFFORT_RE.test(trimmed);
}

